"""Export JSON Schema for each top-level contract to contracts/schema/.

Usage: python -m contracts.export
"""

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from contracts import SCHEMA_VERSION, BudgetState, Decision, Expense, Ruleset

SCHEMA_DIR = Path(__file__).parent / "schema"

TOP_LEVEL: dict[str, type[BaseModel]] = {
    "ruleset": Ruleset,
    "expense": Expense,
    "budget_state": BudgetState,
    "decision": Decision,
}


def render() -> dict[str, str]:
    out: dict[str, str] = {}
    for name, model in TOP_LEVEL.items():
        schema: dict[str, Any] = {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$comment": f"Generated by contracts.export; SCHEMA_VERSION {SCHEMA_VERSION}",
            **model.model_json_schema(),
        }
        out[f"{name}.schema.json"] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    return out


def main() -> None:
    SCHEMA_DIR.mkdir(exist_ok=True)
    for filename, text in render().items():
        (SCHEMA_DIR / filename).write_text(text)


if __name__ == "__main__":
    main()
